"""Generate the fictitious house data for hs26-bmai-w1-opt-rm-house.

Musterwil does not exist. These houses do not exist. These prices are invented.
Nothing in this file is real market data, and nothing derived from it may be
presented as a fact about Swiss housing.

Regenerate with:

    python3 data/generate_houses.py

The seed is fixed, so two runs produce a byte identical data/houses.csv.

Provenance of the design: proposals/cx-house-price-rm.md section 5.
"""
import csv
import os

import numpy as np

SEED = 42
TRUE_W = 9500.0        # CHF per square metre of living area
TRUE_B = 120000.0      # CHF, the base price of a house of zero area
N = 12                 # twelve houses, so the whole table fits on one screen
SIGMA = 25000.0        # CHF, the spread of the asking price around the line
AREA_LO = 90           # smallest living area drawn, in square metres
AREA_HI = 221          # one past the largest living area drawn

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "houses.csv")

HEADER_NOTE = (
    "# Fictitious house data for hs26-bmai-w1-opt-rm-house. "
    "Musterwil is an invented municipality, these houses are invented, "
    "these prices are invented. Generated by data/generate_houses.py, "
    "seed %d. Not real market data." % SEED
)


def make_houses(seed=SEED, n=N):
    """Return (area, price) as float arrays, sorted by area.

    The prices sit on the line price = TRUE_W * area + TRUE_B, displaced by
    Gaussian noise of standard deviation SIGMA, then rounded to the nearest
    thousand francs because asking prices are round numbers.
    """
    rng = np.random.default_rng(seed)
    area = np.sort(rng.integers(AREA_LO, AREA_HI, size=n).astype(float))
    price = TRUE_W * area + TRUE_B + rng.normal(0.0, SIGMA, size=n)
    price = np.round(price / 1000.0) * 1000.0
    return area, price


def write_csv(path=OUT):
    area, price = make_houses()
    with open(path, "w", newline="") as fh:
        fh.write(HEADER_NOTE + "\n")
        # lineterminator is explicit so the file is LF only on every platform.
        # The csv default is CRLF, which would leave this file with mixed
        # endings, because the header note above is written with a plain \n.
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerow(["house_id", "area_m2", "price_chf"])
        for i in range(len(area)):
            writer.writerow([i + 1, "%.0f" % area[i], "%.0f" % price[i]])
    return area, price


if __name__ == "__main__":
    area, price = write_csv()
    print("Wrote %s" % OUT)
    print("Seed %d. Musterwil is fictitious and so are these twelve houses." % SEED)
    print("True line, withheld from the participant until act 4:")
    print("  price = %.0f * area + %.0f   (CHF)" % (TRUE_W, TRUE_B))
    print("  in the working units of the notebook, w = %.1f and b = %.1f"
          % (TRUE_W / 10.0, TRUE_B / 1000.0))
    print("")
    print("  id   area (m2)     price (CHF)")
    for i in range(len(area)):
        print("  %2d      %5.0f       %9.0f" % (i + 1, area[i], price[i]))
